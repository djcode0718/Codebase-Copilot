'use client';
/**
 * components/repo/ExportMenu.tsx
 * Export repository intelligence artifacts as MD, JSON, or TXT.
 */
import { useState, useRef, useEffect } from 'react';
import { Download, FileText, FileJson, FileCode2, ChevronDown } from 'lucide-react';
import { cn } from '@/lib/utils';
import { toast } from 'sonner';
import type { Repo } from '@/lib/types';

interface ExportMenuProps {
  repo: Repo;
  chatMessages?: { role: string; content: string; created_at: string }[];
}

function buildMarkdownReport(repo: Repo): string {
  const now = new Date().toISOString();
  return `# Repository Intelligence Report
**Repository:** ${repo.name}
**Source:** ${repo.source_url}
**Generated:** ${now}
**Status:** ${repo.status}

## Executive Summary
- **Files Indexed:** ${repo.file_count ?? 'N/A'}
- **Knowledge Chunks:** ${repo.node_count ?? 'N/A'}
- **LLM Provider:** ${repo.llm_provider ?? 'N/A'}
- **Index Name:** ${repo.index_name}

## Repository Metrics
| Metric | Value |
|--------|-------|
| Status | ${repo.status} |
| Files | ${repo.file_count ?? 'N/A'} |
| Chunks | ${repo.node_count ?? 'N/A'} |
| Provider | ${repo.llm_provider ?? 'N/A'} |
| Created | ${new Date(repo.created_at).toLocaleString()} |

---
*Generated by Codebase Copilot — Enterprise Repository Intelligence Platform*
`;
}

function buildJsonReport(repo: Repo) {
  return JSON.stringify({
    metadata: {
      generated_at: new Date().toISOString(),
      platform: 'Codebase Copilot',
      version: '2.0',
    },
    repository: {
      id: repo.id,
      name: repo.name,
      source_url: repo.source_url,
      index_name: repo.index_name,
      status: repo.status,
      file_count: repo.file_count,
      node_count: repo.node_count,
      llm_provider: repo.llm_provider,
      created_at: repo.created_at,
    },
  }, null, 2);
}

function buildChatMarkdown(repo: Repo, messages: { role: string; content: string; created_at: string }[]): string {
  const lines = [
    `# Chat Export — ${repo.name}`,
    `**Repository:** ${repo.source_url}`,
    `**Exported:** ${new Date().toISOString()}`,
    '',
    '---',
    '',
  ];
  for (const msg of messages) {
    lines.push(`### ${msg.role === 'user' ? '👤 User' : '🤖 Codebase Copilot'}`);
    lines.push(`*${new Date(msg.created_at).toLocaleString()}*`);
    lines.push('');
    lines.push(msg.content);
    lines.push('');
    lines.push('---');
    lines.push('');
  }
  return lines.join('\n');
}

function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

const EXPORT_OPTIONS = [
  { id: 'md-report',   icon: FileText,  label: 'Repository Report (.md)', desc: 'Markdown summary' },
  { id: 'json-report', icon: FileJson,  label: 'Repository Data (.json)', desc: 'Structured JSON' },
  { id: 'chat-md',     icon: FileCode2, label: 'Chat Export (.md)',        desc: 'Conversation history' },
] as const;

export default function ExportMenu({ repo, chatMessages = [] }: ExportMenuProps) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    function handler(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false);
    }
    document.addEventListener('mousedown', handler);
    return () => document.removeEventListener('mousedown', handler);
  }, []);

  function handleExport(id: typeof EXPORT_OPTIONS[number]['id']) {
    setOpen(false);
    const slug = repo.name.toLowerCase().replace(/\s+/g, '-');
    const ts = new Date().toISOString().slice(0, 10);
    try {
      if (id === 'md-report') {
        downloadFile(buildMarkdownReport(repo), `${slug}-report-${ts}.md`, 'text/markdown');
      } else if (id === 'json-report') {
        downloadFile(buildJsonReport(repo), `${slug}-report-${ts}.json`, 'application/json');
      } else if (id === 'chat-md') {
        if (chatMessages.length === 0) {
          toast.info('No chat messages to export yet.');
          return;
        }
        downloadFile(buildChatMarkdown(repo, chatMessages), `${slug}-chat-${ts}.md`, 'text/markdown');
      }
      toast.success('Export downloaded');
    } catch {
      toast.error('Export failed');
    }
  }

  return (
    <div className="relative" ref={ref}>
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        className="flex items-center gap-1.5 rounded-xl border border-border bg-card/80 px-3 py-2 text-xs text-muted-foreground hover:text-foreground hover:border-border/80 transition-colors cursor-pointer"
      >
        <Download size={13} />
        Export
        <ChevronDown size={11} className={cn('transition-transform', open && 'rotate-180')} />
      </button>

      {open && (
        <div className="absolute right-0 top-full mt-1.5 z-50 w-52 rounded-2xl border border-border bg-card shadow-lg shadow-black/10 overflow-hidden">
          {EXPORT_OPTIONS.map((opt) => (
            <button
              key={opt.id}
              onClick={() => handleExport(opt.id)}
              className="flex w-full items-start gap-3 px-3 py-2.5 text-left text-sm hover:bg-accent transition-colors cursor-pointer"
            >
              <opt.icon size={13} className="text-brand mt-0.5 flex-shrink-0" />
              <div>
                <p className="font-medium text-xs">{opt.label}</p>
                <p className="text-[11px] text-muted-foreground">{opt.desc}</p>
              </div>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

